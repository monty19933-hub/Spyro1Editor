void ArithmeticControls()
{
    foreach(var (word,a,b,result) in new (uint,uint,uint,uint)[]{
        (0x00851020,0x7FFFFFFF,1,0x80000000), // ADD
        (0x20820001,0x7FFFFFFF,0,0x80000000), // ADDI
        (0x00851022,0x80000000,1,0x7FFFFFFF)}) // SUB
    {
        var cpu=new RenderProbeCpu {StrictSignedArithmetic=true};cpu.Copy(codePc,Words(word,0x03E00008,0));
        cpu.Regs[4]=a;cpu.Regs[5]=b;cpu.Regs[2]=0x12345678;cpu.Regs[31]=stop;
        try{cpu.Run(codePc,stop);throw new Exception("Expected native signed trap");}
        catch(RenderProbeArithmeticOverflow e)
        {Check(e.Pc==codePc&&!e.BranchDelaySlot&&cpu.Regs[2]==0x12345678&&cpu.Writes.Count==0,"Signed trap precedes destination/store and reports non-delay context.");}
        cpu.StrictSignedArithmetic=false;cpu.Run(codePc,stop);Check(cpu.Regs[2]==result,"Default legacy arithmetic behavior remains unchanged.");
    }
    foreach(var (word,a,b,result) in new (uint,uint,uint,uint)[]{(0x00851021,0x7FFFFFFF,1,0x80000000),(0x00851023,0,1,0xFFFFFFFF)})
    {
        var cpu=new RenderProbeCpu{StrictSignedArithmetic=true};cpu.Copy(codePc,Words(word,0x03E00008,0));
        cpu.Regs[4]=a;cpu.Regs[5]=b;cpu.Regs[31]=stop;cpu.Run(codePc,stop);
        Check(cpu.Regs[2]==result,"ADDU/SUBU still wrap in strict mode.");
    }
    var delayed=new RenderProbeCpu{StrictSignedArithmetic=true};delayed.Copy(codePc,Words(0x10000001,0x00851020,0x24020055));
    delayed.Regs[4]=0x7FFFFFFF;delayed.Regs[5]=1;delayed.Regs[2]=0x12345678;
    try{delayed.Run(codePc,stop);throw new Exception("Expected branch-delay overflow");}
    catch(RenderProbeArithmeticOverflow e)
    {Check(e.Pc==codePc+4&&e.BranchDelaySlot&&delayed.Regs[2]==0x12345678&&!delayed.Visited.Contains(codePc+8),"Delay-slot trap is distinguished; branch target is not executed.");}
    var load=new RenderProbeCpu{StrictSignedArithmetic=true};load.Copy(codePc,Words(0x8C860000,0x00851020));
    load.Regs[4]=0x80100000;load.Put(0x80100000,0x76543210);load.Regs[5]=0x80000000;load.Regs[2]=0x12345678;
    try{load.Run(codePc,stop);throw new Exception("Expected overflow after load");}
    catch(RenderProbeArithmeticOverflow)
    {Check(load.Regs[6]==0x76543210&&load.Regs[2]==0x12345678,"Prior delayed load retires without a trapping ADD destination write.");}
}
