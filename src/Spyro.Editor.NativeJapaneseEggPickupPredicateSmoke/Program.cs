void Execute(NativeJapaneseEggPickupPredicateSource source, bool certified)
{
    var plan = source.Compile(owner,codePc); byte[] bytes=plan.CopyBytes();
    Check(plan.SourceBound==certified && !plan.DispatchActivated && !plan.PublicationApproved && !plan.RuntimeStackFitProven,
        "Detached predicate evidence never promotes collection or installation.");
    Check(bytes.Length==0x154 && plan.StackByteLength==0x20 && plan.SourceToFinalPc.Count==62,
        "Exact instruction/adapter/stack extents.");
    Check(plan.OperandPatches.Count==4 && plan.OperandPatches.Select(p=>p.UsaAddress).SequenceEqual(
        new uint[]{0x80078A60,0x80078C4C,0x80078AD0,0x80078AD4}),"Explicit nonuniform regional field bindings.");
    var changed=source.Package.Transfers.Where(t=>t.HasDelaySlot&&t.Kind!=NativeMipsBehaviorTransferKind.ReturnRegister)
        .Select(t=>t.SourcePc).Concat(plan.OperandPatches.Select(p=>p.SourcePc)).ToHashSet();
    foreach(var f in source.Package.Fragments)
    for(int i=0;i<f.ByteLength;i+=4)
    {
        uint pc=f.Source.SourcePc+(uint)i;
        if(!changed.Contains(pc))Check(Word(f.CopyBytes(),i)==Word(bytes,(int)(plan.SourceToFinalPc[pc]-codePc)),
            "Every non-transfer/non-global instruction is retained, including native trapping opcodes and delay slots.");
    }
    foreach(var c in cases)
    {
        var cpu=new RenderProbeCpu{StrictSignedArithmetic=true};cpu.Copy(codePc,bytes);
        for(int r=1;r<32;r++)cpu.Regs[r]=0xBA000000u+(uint)r;
        cpu.Hi=0x11223344;cpu.Lo=0x55667788;cpu.Regs[4]=row;cpu.Regs[29]=sp;cpu.Regs[31]=stop;
        uint[] before=cpu.Regs.ToArray();
        void Inputs(RenderProbeCpu target,bool jp)
        {
            target.Put(row+0xC,unchecked((uint)c.X));target.Put(row+0x10,unchecked((uint)c.Y));target.Put(row+0x14,unchecked((uint)c.Z));
            target.Put(row+0x38,unchecked((ushort)c.Height),2);
            uint player=jp?0x80082898u:0x80078A58u;
            target.Put(player,0);target.Put(player+4,0);target.Put(player+8,unchecked((uint)c.PlayerZ));
            target.Put(jp?0x80082A90u:0x80078C4Cu,c.Flags);
            target.Put(jp?0x80082910u:0x80078AD0u,unchecked((uint)c.State));
            target.Put(jp?0x80082914u:0x80078AD4u,unchecked((uint)c.Substate));
            // Wrong uniform-delta flag binding must visibly disagree.
            if(!jp)target.Put(0x80078C50,c.Flags^0x2000);
        }
        Inputs(cpu,false);cpu.Run(plan.EntryPc,stop);
        Check(cpu.Regs[2]==(c.Expected?1u:0u),"Native threshold/state result "+c);
        Check(Enumerable.Range(8,24).All(r=>cpu.Regs[r]==before[r]) && cpu.Hi==0x11223344 && cpu.Lo==0x55667788,
            "All preserved registers, HI/LO and exact SP/RA survive the nested native leaf.");
        Check(cpu.Writes.Count==12 && cpu.Writes.All(p=>p>=sp-0x10 && p<sp-4),"Only three saved registers in the owned 0x20 frame are written.");
        HashSet<uint> reads=[row+0xC,row+0x10,row+0x14,row+0x38,0x80078A58,0x80078A5C,0x80078A60,
            0x80078C4C,0x80078AD0,0x80078AD4,sp-0x10,sp-0xC,sp-8];
        Check(cpu.Reads.All(reads.Contains),"No alias/save/device/effect/model read is reachable.");
        Check(!cpu.Reads.Contains(0x80078AD4)||c.State==15,"Substate is read only for native state15.");
        Check(!cpu.Reads.Contains(0x80078AD0)||(c.Flags&0x2000)==0,"Incompatible player flag short-circuits the state reads.");
        Check(cpu.Calls.SequenceEqual(new[]{plan.SourceToFinalPc[0x80016F74]}),"Only internally owned exact native XY helper is called.");
        Check(!cpu.Visited.Contains(0x8008DFFC)&&!cpu.Visited.Contains(0x80090FA4),"Neither original pickup effects nor donor loop is entered.");
        var original=new RenderProbeCpu{StrictSignedArithmetic=true};original.Copy(0x8008DF64,source.CopyPredicate());original.Copy(0x80016F74,source.CopyDistance());
        // Intercept only the two OUTSIDE endpoints; every predicate/helper instruction remains original.
        original.Copy(0x8008DFFC,Words(0x24020001,0x08004000,0));
        original.Copy(0x80090FA4,Words(0x24020000,0x08004000,0));
        original.Regs[19]=row;original.Regs[30]=0x80082898;original.Regs[29]=sp;Inputs(original,true);
        original.Run(0x8008DF64,stop);
        Check(original.Regs[2]==cpu.Regs[2] && original.Writes.Count==0,"Exact original JP instruction execution agrees and has no direct store.");
    }
    // These are actual trapping ADD/SUB paths, not a C# distance substitute.
    foreach(var (x,y,px,py,trapPc,delay) in new (int,int,int,int,uint,bool)[]{
        (int.MinValue,0,0,0,0x80016F84,false),
        (0,int.MinValue,0,0,0x80016F8C,true),
        (0,0,int.MinValue,0,0x80016F90,false),
        (0,0,0,int.MinValue,0x80016F9C,false),
        (int.MaxValue,0,int.MinValue,0,0x80016F84,false),
        (-800000000,-800000000,0,0,0x80016FC4,false),
        (-1800000000,-1000000000,0,0,0x80016FC4,false),
        (-2000000000,-400000000,0,0,0x80016FD0,true)})
    {
        foreach(bool linked in new[]{false,true})
        {
            var cpu=new RenderProbeCpu{StrictSignedArithmetic=true};
            cpu.Copy(linked?codePc:0x8008DF64,linked?bytes:source.CopyPredicate());
            if(!linked)cpu.Copy(0x80016F74,source.CopyDistance());
            cpu.Regs[4]=row;cpu.Regs[19]=row;cpu.Regs[30]=0x80082898;cpu.Regs[29]=sp;cpu.Regs[31]=stop;
            cpu.Put(row+0xC,unchecked((uint)x));cpu.Put(row+0x10,unchecked((uint)y));
            uint player=linked?0x80078A58u:0x80082898u;cpu.Put(player,unchecked((uint)px));cpu.Put(player+4,unchecked((uint)py));
            try{cpu.Run(linked?plan.EntryPc:0x8008DF64,stop);throw new Exception("Expected native XY overflow");}
            catch(RenderProbeArithmeticOverflow e)
            {
                Check(e.Pc==(linked?plan.SourceToFinalPc[trapPc]:trapPc)&&e.BranchDelaySlot==delay,"Original/linked helper traps at the same instruction and delay context.");
                Check(cpu.Writes.Count==(linked?12:0)&&cpu.Writes.All(p=>p>=sp-0x10&&p<sp-4),"Trap occurs before any collection/global write; no exception-handler execution is claimed.");
            }
        }
    }
    byte[] escaped=plan.CopyBytes();escaped[0]^=1;
    Check(plan.CopyBytes().SequenceEqual(bytes),"Detached byte copies do not mutate the kernel.");
    Refuse(()=>source.Compile(new(domain,0x40,0x150),codePc),"exact aligned");
    Refuse(()=>source.Compile(owner,codePc+1),"exact aligned");
    Refuse(()=>source.Compile(owner,0x801FFF00),"exact aligned");
    Refuse(()=>source.Compile(owner,0x80078A00),"player");
    Refuse(()=>source.Compile(new(new(NativeAddressKind.LevelData,"wrong",NativeAddressRevision.Original,0x1000),0,0x154),codePc),"exact aligned");
}

void RegionalStateConsumers(NativeRegionalSourceSession jp,NativeRegionalSourceSession usa)
{
    foreach(var session in new[]{jp,usa})
    {
        bool j=ReferenceEquals(session,jp);uint pc=j?0x8003610Cu:0x80034EE0u;
        uint state=j?0x80082910u:0x80078AD0u,sub=state+4;
        foreach(int s in new[]{-1,0,14,15,16})foreach(int t in new[]{-1,0,1,11,12})
        {
            var cpu=new RenderProbeCpu{StrictSignedArithmetic=true};cpu.Copy(pc,session.ReadExecutableRange(pc-0x8000F800,0x28));
            cpu.Copy(pc+0x28,Words(0x24020001,0x08004000,0));
            cpu.Copy(j?0x80036170u:0x80034F40u,Words(0x24020000,0x08004000,0));
            cpu.Put(state,unchecked((uint)s));cpu.Put(sub,unchecked((uint)t));cpu.Run(pc,stop);
            Check(cpu.Regs[2]==(s==15&&t==11?1u:0u)&&cpu.Writes.Count==0,"Both regional state consumers select the same exact state15/substate11 values despite scheduling changes.");
            Check(cpu.Reads.All(a=>a==state||a==sub),"Regional state consumer reads its pinned semantic fields only.");
        }
        pc=j?0x8004E62Cu:0x8004A200u;uint flag=j?0x80082A90u:0x80078C4Cu;
        foreach(uint bits in new uint[]{0,1,0x1000,0x2000,0x4000,0xFFFFFFFF})
        {
            var cpu=new RenderProbeCpu{StrictSignedArithmetic=true};cpu.Copy(pc,session.ReadExecutableRange(pc-0x8000F800,0x20));
            cpu.Copy(pc+0x20,Words(0x24020000,0x08004000,0));cpu.Copy(pc+0x34,Words(0x24020001,0x08004000,0));
            cpu.Put(flag,bits);cpu.Regs[29]=sp;cpu.Run(pc,stop);
            Check(cpu.Regs[2]==((bits&0x2000)!=0?1u:0u)&&cpu.Reads.SequenceEqual(new[]{flag}),"Matching regional bit2000 tests read the NONuniformly shifted flag owner.");
        }
    }
}

