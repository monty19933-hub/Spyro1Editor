int checks = 0;
void Check(bool value, string why) { if (!value) throw new Exception(why); checks++; }
void Refuse(Action action, string needle)
{
    try { action(); } catch (InvalidDataException e) when (e.Message.Contains(needle, StringComparison.Ordinal)) { checks++; return; }
    throw new Exception("Expected specific refusal: " + needle);
}
static byte[] Words(params uint[] words)
{ byte[] b = new byte[words.Length * 4]; for (int i = 0; i < words.Length; i++) BinaryPrimitives.WriteUInt32LittleEndian(b.AsSpan(i * 4), words[i]); return b; }
static uint Word(byte[] b, int at) => BinaryPrimitives.ReadUInt32LittleEndian(b.AsSpan(at));
