namespace Spyro.Editor.Core.Editing;

/// <summary>How the game itself arranges its objects, measured over its thirty levels on foot (the editor's level cache;
/// study mine.py): every little group of loose gems, chests, enemies and animals that stand within a few steps of one
/// another, with the kind of place the group is at (in a corner, by a wall, on a narrow way, out in the open, on a raised
/// place) and each object's place measured from the foot of the nearest wall: along the wall and out from it. Two
/// thirds of the game's groups are in corners or on raised places; one in seven is out in the open.
/// <see cref="LevelScatter"/> sets a generated level's objects up from these, a group at a time, at a place of the same
/// kind. Only kinds and distances are kept: no level data.</summary>
internal static class RetailArrangements
{
    public enum Where { Corner, Wall, Way, Open, Raised }

    /// <summary>One object of a group: a gem ('g', its value), a chest ('B' basket, 'S' strong, 'F' three-flame, 'W'
    /// firework, 'P' spring), an enemy ('E') or an animal ('A'); <see cref="U"/> along the wall from the group's middle,
    /// <see cref="V"/> out from the wall's foot (for a group with no wall near: from the group's middle).</summary>
    public readonly record struct Member(char Kind, int Value, int U, int V);

    /// <param name="Wall">How far the group's middle is from the nearest wall (999: none within reach).</param>
    public sealed record Arrangement(Where At, int Wall, Member[] Members)
    {
        /// <summary>Whether the members are measured from a wall's foot (else from the group's own middle).</summary>
        public bool FromWall => Wall <= 360;
        public double MiddleV => Members.Average(m => m.V);
    }

    public static readonly IReadOnlyList<Arrangement> All = Parse();
    public static readonly ILookup<Where, Arrangement> By = All.ToLookup(a => a.At);

    private static List<Arrangement> Parse()
    {
        var list = new List<Arrangement>();
        foreach (string line in Data.Split('\n', StringSplitOptions.RemoveEmptyEntries))
        {
            int colon = line.IndexOf(':');
            var at = line[0] switch { 'c' => Where.Corner, 'w' => Where.Wall, 'y' => Where.Way, 'o' => Where.Open, _ => Where.Raised };
            var members = line[(colon + 1)..].Split(';').Select(part =>
            {
                string[] f = part.Split(',');
                return new Member(f[0][0], f[0].Length > 1 ? int.Parse(f[0][1..]) : 0, int.Parse(f[1]), int.Parse(f[2]));
            }).ToArray();
            list.Add(new(at, int.Parse(line[1..colon]), members));
        }
        return list;
    }

