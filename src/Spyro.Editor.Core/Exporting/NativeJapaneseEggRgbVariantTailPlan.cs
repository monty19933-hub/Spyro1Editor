    public static NativeJapaneseEggRgbVariantTailPlan Capture(NativeRegionalSourceSession usa,
        NativeJapaneseEggArtisansIntegrationPlan integration,NativeJapaneseEggRgbEditPlan first,NativeJapaneseEggRgbEditPlan second)
    {
        ArgumentNullException.ThrowIfNull(usa);ArgumentNullException.ThrowIfNull(integration);
        ArgumentNullException.ThrowIfNull(first);ArgumentNullException.ThrowIfNull(second);
        if(usa.Revision!=NativeDiscRevision.UsaScus94228||!integration.SourceCertified||!first.SourceAncestryCertified||!second.SourceAncestryCertified||
            first.Source.AssetAncestor.UsaSourceImageSha256!=usa.SourceImageSha256||
            !usa.ReadWadEntry(10).AsSpan().SequenceEqual(integration.CopyOriginalLevelData())||
            !usa.ReadExecutableRange(0,usa.ExecutableByteLength).AsSpan().SequenceEqual(integration.CopyOriginalExecutable()))
            throw new InvalidDataException("RGB tail requires the exact USA source, matching regional RGB issuer and source-issued Artisans integration.");
        var result=new NativeJapaneseEggRgbVariantTailPlan(integration,first,second,true);usa.VerifyUnchanged();return result;
    }
