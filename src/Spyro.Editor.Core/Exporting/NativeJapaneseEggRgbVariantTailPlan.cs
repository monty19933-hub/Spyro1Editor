    public byte[] RevertExact(ReadOnlySpan<byte> afterimage)
    {
        RequireFinal(afterimage);byte[] inverse=new byte[_before.Length];afterimage[..0x800].CopyTo(inverse);
        foreach(var s in _growth.Subfiles)
        {
            afterimage.Slice(s.FinalOffset,s.OriginalLength).CopyTo(inverse.AsSpan(s.OriginalOffset));
            Put(inverse,s.Index*8,(uint)s.OriginalOffset);Put(inverse,s.Index*8+4,(uint)s.OriginalLength);
        }
        if(!inverse.AsSpan().SequenceEqual(_before))throw new InvalidDataException("RGB tail inverse lost a current-body owner.");
        return inverse;
    }
