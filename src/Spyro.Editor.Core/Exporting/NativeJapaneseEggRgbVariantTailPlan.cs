    private NativeJapaneseEggRgbVariantTailPlan(NativeJapaneseEggArtisansIntegrationPlan integration,
        NativeJapaneseEggRgbEditPlan first,NativeJapaneseEggRgbEditPlan second,bool certified)
    {
        if(integration.SourceCertified!=certified||first.SourceAncestryCertified!=certified||second.SourceAncestryCertified!=certified||
            !ReferenceEquals(first.Source,second.Source)||
            !integration.VisualAncestor.ModelAssembly.CopyModelPackage().AsSpan().SequenceEqual(first.CopyOriginalPackage())||
            !first.CopyOriginalPackage().AsSpan().SequenceEqual(second.CopyOriginalPackage()))
            throw new InvalidDataException("RGB tail needs one exact regional model ancestry and the actual matching Artisans composition.");
        Integration=integration;SourceCertified=certified;_variants=[first,second];
        _before=integration.CopyLevelData();CurrentDataSha256=Hash(_before);
        if(CurrentDataSha256!=integration.LevelDataSha256||integration.Rows.Count!=2)
            throw new InvalidDataException("RGB tail current body or its two intended rows changed.");
        OriginalModelOffset=Int(_before,0x10);OriginalModelLength=Int(_before,0x14);
        var registrations=NativeMobyRegistrationTableLayout.Decode(_before.AsSpan(0,0x800),OriginalModelOffset,OriginalModelLength);
        if(registrations.Registrations.Count(r=>r.ActorId==0xF5)!=1)
            throw new InvalidDataException("The canonical class F5 registration must remain unique.");
        byte[][] packages=_variants.Select(v=>v.CopyPackage()).ToArray();
        int payloadLength=checked(packages[0].Length+packages[1].Length);byte[] append=new byte[payloadLength];
        packages[0].CopyTo(append,0);packages[1].CopyTo(append,packages[0].Length);
        // The existing whole-body growth grammar owns all descriptor/old-root
        // shifts. No model-tail class is invented to carry an unregistered root.
        _growth=new(_before.AsSpan(0,0x800),_before.Length,[new(0,0,0,0,OriginalModelLength,0,append,2,false)]);
        _after=_growth.Expand(_before);FinalDataSha256=Hash(_after);GrowthBytes=_growth.Growth;
        if(GrowthBytes!=((payloadLength+0x7FF)&~0x7FF)||_growth.Subfiles[2].Growth!=GrowthBytes||
            _growth.Subfiles[2].FinalOffset!=OriginalModelOffset||
            !_before.AsSpan(0x50,0x180).SequenceEqual(_after.AsSpan(0x50,0x180)))
            throw new InvalidDataException("Unregistered RGB tail changed model roots/classes or unexpected outer geometry.");
        var finalRegistrations=NativeMobyRegistrationTableLayout.Decode(_after.AsSpan(0,0x800),OriginalModelOffset,Int(_after,0x14));
        if(!registrations.Registrations.SequenceEqual(finalRegistrations.Registrations))
            throw new InvalidDataException("RGB tail must not register either new package or alter any old registration.");
        // Original here means this transaction's current detached beforeimage,
        // not a recertification of generated bytes as original retail source.
        BeforeDomain=new(NativeAddressKind.LevelData,"detached-current-f5:"+CurrentDataSha256,NativeAddressRevision.Original,_before.Length);
        FinalDomain=new(NativeAddressKind.LevelData,"detached-f5-rgb-tail:"+FinalDataSha256,NativeAddressRevision.Final,_after.Length);
        List<NativeRelocationRegion> regions=[new("header",new(BeforeDomain,0,0x800),new(FinalDomain,0,0x800),0x800)];
        foreach(var s in _growth.Subfiles)
        {
            regions.Add(new("retained-subfile-"+s.Index,new(BeforeDomain,s.OriginalOffset,s.OriginalLength),new(FinalDomain,s.FinalOffset,s.OriginalLength),0x800));
            if(!_before.AsSpan(s.OriginalOffset,s.OriginalLength).SequenceEqual(_after.AsSpan(s.FinalOffset,s.OriginalLength)))
                throw new InvalidDataException("RGB tail changed a retained subfile, including its complete scene/fixups complement.");
        }
        var before=NativeLevelRuntimeMemoryReport.DecodeFixture(10,_before,integration.FinalCopyBufferAddress);
        var after=NativeLevelRuntimeMemoryReport.DecodeFixture(10,_after,integration.FinalCopyBufferAddress);
        var actual=integration.RuntimeMemory;
        if(before.ModelRamStart!=actual.ModelRamStart||before.SceneRamStart!=actual.SceneRamStart||
            before.SceneReadEnd!=actual.SceneReadEnd||before.NormalReservedBufferStart!=actual.NormalReservedBufferStart||
            before.ModelBytesRead!=actual.ModelBytesRead||before.MobyTableRamStart!=actual.MobyTableRamStart||
            certified&&!actual.NativeSourceCertified)
            throw new InvalidDataException("Neutral address projection disagrees with the actual integration's normal-load ancestry.");
        if(after.ModelRamStart!=before.ModelRamStart||after.SceneRamStart!=before.SceneRamStart+GrowthBytes||
            after.SceneReadEnd!=before.SceneReadEnd+GrowthBytes||after.ModelBytesRead!=before.ModelBytesRead+GrowthBytes||
            after.MobyTableRamStart!=before.MobyTableRamStart+GrowthBytes||after.PlacedMobyCount!=before.PlacedMobyCount||
            after.DynamicMobyCapacity!=before.DynamicMobyCapacity||!after.KnownPostLoadExtentsDisjoint)
            throw new InvalidDataException("RGB tail exceeds or disagrees with the existing normal model/scene read layout.");
        ProjectedModelRamStart=after.ModelRamStart;ProjectedSceneRamStart=after.SceneRamStart;
        ProjectedSceneReadEnd=after.SceneReadEnd;ProjectedNormalGap=after.NormalReservedBufferGapBytes;
        _packages=new(StringComparer.Ordinal);List<NativeJapaneseEggRgbVariantOwner> owners=[];List<NativeJapaneseEggRgbVariantRow> rows=[];
        int cursor=OriginalModelOffset+OriginalModelLength;
        for(int i=0;i<2;i++)
        {
            var row=integration.Rows[i];var edit=_variants[i];var extent=new NativeByteExtent(FinalDomain,cursor,packages[i].Length);
            uint root=checked(after.ModelRamStart+(uint)(cursor-OriginalModelOffset));
            _packages.Add(row.Placement.Id,extent);regions.Add(new("rgb-variant-"+row.Placement.Id,null,extent,4));
            if(!_after.AsSpan(cursor,packages[i].Length).SequenceEqual(packages[i]))
                throw new InvalidDataException("Complete source-form variant is not installed in its exact owner.");
            var fields=edit.Source.AssetAncestor.ProjectLoaderAddresses(root);
            foreach(var field in fields)
                if(Word(packages[i],field.PackageFieldOffset)!=field.SourceWord||field.RuntimeTargetAddress<root||
                    field.RuntimeTargetAddress+4>root+packages[i].Length)
                    throw new InvalidDataException("RGB variant pointer projection leaves its actual package or pre-rebases disk bytes.");
            owners.Add(new(row.Placement.Id,cursor,packages[i].Length,root,edit.VariantIdentity,edit.FinalPackageSha256,fields));
            rows.Add(new(row.Placement.Id,row.NativeIndex,row.RowSceneOffset,checked(after.SceneRamStart+(uint)row.RowSceneOffset),
                checked(after.SceneRamStart+(uint)row.PrivateSceneOffset),root));
            cursor+=packages[i].Length;
        }
        int tailEnd=OriginalModelOffset+Int(_after,0x14);PaddingByteLength=tailEnd-cursor;
        if(PaddingByteLength>0)
        {
            PaddingOwner=new(FinalDomain,cursor,PaddingByteLength);regions.Add(new("new-sector-padding",null,PaddingOwner,4));
            if(_after.AsSpan(cursor,PaddingByteLength).ContainsAnyExcept((byte)0))throw new InvalidDataException("New model alignment bytes are not zero.");
        }
        if(tailEnd!=Int(_after,0x18)||owners[0].ProjectedLoadedRoot+owners[0].ByteLength!=owners[1].ProjectedLoadedRoot||
            owners[1].ProjectedLoadedRoot+owners[1].ByteLength+PaddingByteLength!=after.SceneRamStart||
            rows.Select(r=>r.ProjectedRowAddress).Distinct().Count()!=2||rows.Select(r=>r.ProjectedPrivateAddress).Distinct().Count()!=2)
            throw new InvalidDataException("Variant/scene owners do not form independent complete normal-load extents.");
        Variants=owners.AsReadOnly();Rows=rows.AsReadOnly();Layout=new(BeforeDomain,FinalDomain,regions);
        SceneOwner=new(FinalDomain,Int(_after,0x18),Int(_after,0x1C));
        if(!CopyScene().AsSpan().SequenceEqual(integration.CopyScene()))throw new InvalidDataException("Complete scene changed during RGB model growth.");
        var currentRead=new NativeMobyDependencyRead("complete-detached-current",new(BeforeDomain,0,_before.Length),CurrentDataSha256);
        var preserved=_growth.Subfiles.Select(s=>new NativeMobyDependencyPreservation(currentRead.Id,s.OriginalOffset,
            new(FinalDomain,s.FinalOffset,s.OriginalLength))).Prepend(new(currentRead.Id,0x50,new(FinalDomain,0x50,0x7B0))).ToArray();
        List<NativeMobyDependencyNode> nodes=[new("f5.rgb.current",NativeMobyDependencyKind.RuntimeBuffer,
            NativeMobyDependencyResolution.DestinationResident,NativeMobyDependencySharing.Immutable,CurrentDataSha256,[],[currentRead],Preserved:preserved)];
        List<string> roots=[];
        for(int i=0;i<2;i++)
        {
            var edit=_variants[i];var owner=owners[i];string id="f5.rgb.variant."+owner.IntendedRowId;roots.Add(id);
            var asset=edit.Source.AssetAncestor;
            var read=new NativeMobyDependencyRead("original-native-rgb-model",new(asset.OriginalDataDomain,asset.SourceRootDataOffset,asset.Model.PackageByteLength),edit.OriginalPackageSha256);
            var target=VariantExtent(owner.IntendedRowId);
            nodes.Add(new(id,NativeMobyDependencyKind.ActorPackage,NativeMobyDependencyResolution.ImportFromSource,
                NativeMobyDependencySharing.Immutable,edit.VariantIdentity,["f5.rgb.current"],[read],
                context=>new(edit.ApplyExact(context.Read(read.Id)),[new("unregistered-rgb-package",target)],[])));
        }
        byte[] Read(NativeByteExtent e)=>ReferenceEquals(e.Space,BeforeDomain)?_before.AsSpan((int)e.Offset,(int)e.ByteLength).ToArray():first.Source.AssetAncestor.ReadSource(e);
        Graph=NativeMobyDependencyClosureCompiler.Compile(nodes,roots,Read);Graph.RequirePreservedFinalBytes(FinalDomain,_after,Read);
        foreach(var install in Graph.Installs)
            if(!ReferenceEquals(install.Destination.Space,FinalDomain)||
                !_after.AsSpan((int)install.Destination.Offset,(int)install.Destination.ByteLength).SequenceEqual(Graph.CopyPayload(install.NodeId)))
                throw new InvalidDataException("RGB dependency output is not installed in its exact final package owner.");
        PlanSha256=Hash(Encoding.UTF8.GetBytes("jp-f5-unregistered-rgb-tail-v1\n"+integration.PlanSha256+"\n"+CurrentDataSha256+"\n"+
            FinalDataSha256+"\n"+Graph.Fingerprint+"\n"+string.Join('\n',owners.Select(v=>v.IntendedRowId+":"+v.VariantIdentity))+"\n"));
        _=RevertExact(_after);
    }
